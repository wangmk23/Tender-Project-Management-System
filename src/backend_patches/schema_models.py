def _validate_identifier(identifier: str) -> str:
    value = str(identifier or "").strip()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError(f"invalid SQL identifier: {identifier!r}")
    return value


def table_columns(bind_or_db: Any, table_name: str, sql_text: Any = None) -> set[str]:
    """Return existing column names for *table_name* across DB-API, SQLAlchemy binds, or execute callables."""
    safe_table = _validate_identifier(table_name)
    pragma_sql = f"PRAGMA table_info({safe_table})"
    target = getattr(bind_or_db, "session", bind_or_db)
    if callable(target) and not hasattr(target, "execute"):
        try:
            res = target(pragma_sql)
        except TypeError:
            wrapper = sql_text or text
            res = target(wrapper(pragma_sql))
    elif hasattr(target, "execute"):
        wrapper = sql_text or text
        if getattr(target, "_consortium_raw_sql", False):
            res = target.execute(pragma_sql, {})
        else:
            try:
                res = target.execute(wrapper(pragma_sql))
            except TypeError:
                res = target.execute(pragma_sql)
    elif hasattr(bind_or_db, "cursor"):
        cur = bind_or_db.cursor()
        try:
            res = cur.execute(pragma_sql).fetchall()
        finally:
            cur.close()
    else:
        raise TypeError(f"unsupported database bind for table_columns: {type(bind_or_db)!r}")

    if hasattr(res, "fetchall"):
        rows = res.fetchall()
    elif hasattr(res, "all"):
        rows = res.all()
    else:
        rows = list(res)

    result: set[str] = set()
    for row in rows:
        if hasattr(row, "_mapping") and "name" in row._mapping:
            result.add(str(row._mapping["name"]))
        elif isinstance(row, dict) and "name" in row:
            result.add(str(row["name"]))
        elif hasattr(row, "keys") and "name" in row.keys():
            result.add(str(row["name"]))
        elif len(row) > 1:
            result.add(str(row[1]))
    return result


def has_table_column(bind_or_db: Any, table_name: str, column_name: str) -> bool:
    return str(column_name) in table_columns(bind_or_db, table_name)


def expected_table_columns(
    table_name: str, *, include_extensions: bool = True
) -> tuple[str, ...]:
    spec = TABLE_SPECS[table_name]
    return tuple(
        col["name"]
        for col in spec["columns"]
        if include_extensions or not col.get("is_extension")
    )


def verify_host_orm_mirror(host_source: Any) -> dict[str, Any]:
    """Compare the 18 core ORM models on *host_source* against TABLE_SPECS."""
    getter = (
        (lambda k: host_source.get(k))
        if isinstance(host_source, dict)
        else (lambda k: getattr(host_source, k, None))
    )
    matched_models: list[str] = []
    missing_models: list[str] = []
    column_drifts: dict[str, dict[str, list[str]]] = {}
    extension_gaps: dict[str, list[str]] = {}

    for model_name, table_name in sorted(CORE_ORM_TABLE_MAP.items()):
        model_cls = getter(model_name)
        if model_cls is None or not hasattr(model_cls, "__table__"):
            missing_models.append(model_name)
            continue
        actual_cols = {col.name for col in model_cls.__table__.columns}
        core_expected = set(expected_table_columns(table_name, include_extensions=False))
        full_expected = set(expected_table_columns(table_name, include_extensions=True))
        missing_core = sorted(core_expected - actual_cols)
        unexpected = sorted(actual_cols - full_expected)
        missing_ext = sorted((full_expected - core_expected) - actual_cols)
        if missing_ext:
            extension_gaps[model_name] = missing_ext
        if missing_core or unexpected:
            column_drifts[model_name] = {
                "missing_core": missing_core,
                "unexpected": unexpected,
            }
        else:
            matched_models.append(model_name)

    return {
        "signature": SCHEMA_MODELS_SIGNATURE,
        "total_core_models": len(CORE_ORM_TABLE_MAP),
        "matched_core_models": len(matched_models),
        "missing_models": missing_models,
        "column_drifts": column_drifts,
        "known_extension_gaps_in_core_orm": extension_gaps,
        "passed": not missing_models and not column_drifts,
    }


def verify_database_schema(
    bind_or_db: Any, *, tables: tuple[str, ...] | list[str] | None = None
) -> dict[str, Any]:
    """Verify SQLite table columns against TABLE_SPECS."""
    target_tables = list(tables) if tables is not None else sorted(TABLE_SPECS)
    verified: list[str] = []
    absent_optional: list[str] = []
    missing_columns: dict[str, list[str]] = {}

    for table_name in target_tables:
        spec = TABLE_SPECS[table_name]
        actual = table_columns(bind_or_db, table_name)
        if not actual:
            absent_optional.append(table_name)
            continue
        core_cols = set(expected_table_columns(table_name, include_extensions=False))
        missing = sorted(core_cols - actual)
        if missing:
            missing_columns[table_name] = missing
        else:
            verified.append(table_name)

    return {
        "signature": SCHEMA_MODELS_SIGNATURE,
        "checked_tables": len(target_tables),
        "verified_present_tables": len(verified),
        "absent_tables": absent_optional,
        "missing_core_columns": missing_columns,
        "passed": not missing_columns,
    }


def register(app: Any, db: Any = None, host_module: Any = None) -> dict[str, Any]:
    """Attach the declarative schema registry and verification summary to *app*."""
    if os.environ.get("PM_SKIP_SCHEMA_MIRROR") == "1":
        state = {"signature": SCHEMA_MODELS_SIGNATURE, "skipped": True, "passed": True}
        if hasattr(app, "extensions"):
            app.extensions["schema_registry"] = state
        return state

    orm_report = verify_host_orm_mirror(host_module) if host_module is not None else None
    registry_state = {
        "signature": SCHEMA_MODELS_SIGNATURE,
        "table_count": len(TABLE_SPECS),
        "core_orm_count": len(CORE_ORM_TABLE_MAP),
        "mirror_metadata": MIRROR_METADATA,
        "mirror_tables": MIRROR_TABLES,
        "core_orm_mirrors": CORE_ORM_MIRRORS,
        "orm_verification": orm_report,
        "passed": True if orm_report is None else bool(orm_report.get("passed")),
    }
    if hasattr(app, "extensions"):
        app.extensions["schema_registry"] = registry_state
    return registry_state
