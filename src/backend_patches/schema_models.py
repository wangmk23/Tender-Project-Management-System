def _sqlalchemy_type(sql_type_str: str):
    raw = (sql_type_str or "TEXT").strip().upper()
    if raw.startswith("VARCHAR"):
        m = re.search(r"\((\d+)\)", raw)
        return String(int(m.group(1)) if m else 255)
    if raw.startswith("NUMERIC"):
        m = re.search(r"\((\d+)\s*,\s*(\d+)\)", raw)
        if m:
            return Numeric(int(m.group(1)), int(m.group(2)))
        return Numeric(15, 2)
    if raw == "BIGINT":
        return BigInteger()
    if raw == "INTEGER":
        return Integer()
    if raw == "BOOLEAN":
        return Boolean()
    if raw == "DATE":
        return Date()
    if raw == "DATETIME":
        return DateTime()
    if raw == "FLOAT":
        return Float()
    if raw == "BLOB":
        return LargeBinary()
    if raw == "JSON":
        return JSON()
    return Text()


MIRROR_METADATA = MetaData()
MirrorBase = declarative_base(metadata=MIRROR_METADATA)
MIRROR_TABLES: dict[str, Table] = {}


def _build_mirror_tables() -> None:
    for table_name, spec in TABLE_SPECS.items():
        cols = []
        for col in spec["columns"]:
            cols.append(
                Column(
                    col["name"],
                    _sqlalchemy_type(col["type"]),
                    primary_key=bool(col.get("pk")),
                    nullable=not bool(col.get("notnull")) and not bool(col.get("pk")),
                )
            )
        idxs = []
        for idx in spec.get("indexes", []):
            idx_name = idx.get("name", "")
            idx_cols = idx.get("columns", [])
            if idx_name and not idx_name.startswith("sqlite_autoindex_") and idx_cols:
                idxs.append(Index(idx_name, *idx_cols, unique=bool(idx.get("unique"))))
        MIRROR_TABLES[table_name] = Table(table_name, MIRROR_METADATA, *cols, *idxs)


_build_mirror_tables()

